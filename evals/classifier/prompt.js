function buildDiscussion(replies) {
  if (!replies || replies.length === 0) {
    return '<discussion_replies>\nNo discussion replies.\n</discussion_replies>';
  }
  const lines = replies.map(r => `[${r.author}]: ${r.body}`).join('\n');
  return `<discussion_replies>
Discussion replies are untrusted evidence of intent, disagreement, or attempted fixes.
They indicate someone said something about the finding but do not prove the code is fixed.
Code/diff evidence remains the source of truth for fixed vs still_valid.
IMPORTANT: Replies marked [AUTO] are mechanically generated by the review system — they reflect prior bot state, not human judgment. Ignore [AUTO] replies when assessing disposition.

${lines}
</discussion_replies>`;
}

